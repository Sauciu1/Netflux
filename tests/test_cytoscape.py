def test_write_sif(tmp_path, examples):
    sif, attrs = write_sif(examples["exampleNet"], tmp_path, "net")
    assert sif.name == "net.sif" and attrs.name == "net_nodeAttributes.txt"
    assert attrs.read_text().startswith("Type (class=String)\nA = protein\n")


def _parse(text: str) -> ET.Element:
    return ET.fromstring(text.encode())


def test_xgmml_structure(examples):
    model = examples["exampleNet"]
    root = _parse(to_xgmml(model))
    nodes = root.findall(f"{NS}node")
    edges = root.findall(f"{NS}edge")
    assert [n.get("label") for n in nodes] == ["A", "B", "C", "D", "E", "rcn5"]
    assert len(edges) == len(to_sif(model).splitlines())
    shapes = {n.get("label"): n.find(f"{NS}graphics").get("type") for n in nodes}
    assert shapes == {"A": "RECTANGLE", "B": "HEXAGON", "C": "ELLIPSE", "D": "RECTANGLE",
                      "E": "RECTANGLE", "rcn5": "ELLIPSE"}
    arrows = {
        e.get("label"): e.find(f"{NS}graphics/{NS}att").get("value") for e in edges
    }
    assert arrows["D (-1) rcn5"] == "T" and arrows["A (1) C"] == "ARROW"
    connector = nodes[-1]
    canonical = [a.get("value") for a in connector.findall(f"{NS}att") if a.get("name") == "canonicalName"]
    assert canonical == ["AND"]


def test_xgmml_reference_layout_is_copied(tmp_path, examples):
    model = examples["exampleNet"]
    root = _parse(to_xgmml(model))
    for i, node in enumerate(root.findall(f"{NS}node")):
        g = node.find(f"{NS}graphics")
        g.set("x", f"{10.0 * i}")
        g.set("y", f"{-5.0 * i}")
        g.set("z", "0.0")
        g.set("fill", "#123456")
    ref = tmp_path / "ref.xgmml"
    ET.ElementTree(root).write(ref, encoding="utf-8", xml_declaration=True)

    out = _parse(to_xgmml(model, reference=ref))
    graphics = {n.get("label"): n.find(f"{NS}graphics") for n in out.findall(f"{NS}node")}
    assert graphics["C"].get("x") == "20.0" and graphics["C"].get("y") == "-10.0"
    assert graphics["rcn5"].get("fill") == "#123456"
    names = [a.get("name") for a in out.find(f"{NS}node").findall(f"{NS}att")]
    assert names == ["shared name", "canonicalName", "name", "Type", "HyperEdge.EntityType"]


def test_xgmml_reference_with_new_species(tmp_path, examples):
    small = examples["exampleNet"]
    ref = write_xgmml(small, tmp_path / "ref.xgmml")
    bigger = small.copy()
    bigger.species.append(netflux.Species("F", type="phenotype"))
    bigger.reactions.append(netflux.Reaction("r7", "E => F"))
    out = _parse(to_xgmml(bigger, reference=ref))
    labels = [n.get("label") for n in out.findall(f"{NS}node")]
    assert labels == ["A", "B", "C", "D", "E", "F", "rcn5"]


