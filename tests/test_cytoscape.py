import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

import netflux
from netflux import read_model, to_node_attributes, to_sif, to_xgmml, write_sbgn_style, write_sif, write_xgmml

from .conftest import complete_fixtures, fixture_id

NS = "{http://www.cs.rpi.edu/XGMML}"
FIXTURES = complete_fixtures()


@pytest.mark.skipif(not FIXTURES, reason="Autogenerated models folder not available")
@pytest.mark.parametrize("xls", FIXTURES, ids=fixture_id)
def test_sif_matches_matlab_output_byte_for_byte(xls):
    stem = xls.with_suffix("")
    model = read_model(xls)
    assert to_sif(model) == Path(f"{stem}.sif").read_text()
    assert to_node_attributes(model) == Path(f"{stem}_nodeAttributes.txt").read_text()


def test_and_gates_use_connectors(examples):
    model = examples["ryall_cardiomyocyte_hypertrophy_jbc2012"]
    k = model.reaction_ids.index(
        next(r.id for r in model.reactions if r.rule == "!cFos & !cJun & !NFAT => SERCA")
    ) + 1
    lines = to_sif(model).splitlines()
    start = lines.index(f"rcn{k}\t1\tSERCA")
    assert lines[start + 1 : start + 4] == [
        f"{s}\t-1\trcn{k}" for s in sorted(["cFos", "cJun", "NFAT"], key=model.species_ids.index)
    ]
    assert f"rcn{k} = connector" in to_node_attributes(model)


