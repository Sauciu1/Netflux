import math
import random

import pytest
import torch

import netflux
from netflux import NetfluxODE, hill

from .conftest import complete_fixtures, matlab_act, matlab_rhs, model_params, native_rhs

F64 = torch.float64


@pytest.mark.parametrize("n,ec50", [(1.4, 0.5), (2.0, 0.3), (3.0, 0.6), (1.0, 0.25)])
def test_hill_identities(n, ec50):
    x = torch.tensor([0.0, ec50, 1.0], dtype=F64)
    assert hill(x, n, ec50).tolist() == pytest.approx([0.0, 0.5, 1.0], abs=1e-12)


def test_hill_is_clamped():
    h = hill(torch.tensor([-1e-9, 2.0, 5.0], dtype=F64), 1.4, 0.5)
    assert h[0] == 0.0 and torch.all(h <= 1.0)


@pytest.mark.parametrize("x", [0.0, 0.2, 0.5, 0.9, 1.0, 1.7])
def test_weighted_hill_equals_matlab_act(x):
    assert 0.7 * float(hill(torch.tensor(x, dtype=F64), 1.4, 0.5)) == pytest.approx(matlab_act(x, 0.7, 1.4, 0.5))


def _random_states(n_species: int, count: int = 3, seed: int = 0):
    rng = random.Random(seed)
    return [[rng.uniform(0.0, 1.2) for _ in range(n_species)] for _ in range(count)]


def _assert_matches_matlab(model):
    params = model_params(model)
    for y in _random_states(len(model.species)):
        expected = matlab_rhs(model, y, *params)
        assert native_rhs(model, y) == pytest.approx(expected, rel=1e-12, abs=1e-12)


@pytest.mark.parametrize("name", netflux.list_examples())
def test_rhs_matches_matlab_reference_on_examples(examples, name):
    _assert_matches_matlab(examples[name])


@pytest.mark.parametrize("xls", complete_fixtures()[::17], ids=lambda p: p.parent.name)
def test_rhs_matches_matlab_reference_on_autogenerated(xls):
    _assert_matches_matlab(netflux.read_model(xls))


def test_rhs_with_zero_weight_and_gate(examples):
    model = examples["exampleNet"].copy()
    model.get_reaction("r5").weight = 0.0  # C & !D => E
    params = model_params(model)
    y = [0.4, 0.2, 0.9, 0.1, 0.3]
    assert native_rhs(model, y) == pytest.approx(matlab_rhs(model, y, *params), abs=1e-12)


def test_batched_parameters_match_loop(examples):
    model = examples["ryall_cardiomyocyte_hypertrophy_jbc2012"]
    w, n, ec50, ymax, tau = (torch.tensor(v, dtype=F64) for v in model_params(model))
    torch.manual_seed(0)
    batch = 4
    wb = torch.rand(batch, w.shape[0], dtype=F64)
    yb = torch.rand(batch, len(model.species), dtype=F64)
    batched = NetfluxODE(model.topology, wb, n, ec50, ymax, tau)(torch.tensor(0.0), yb)
    for b in range(batch):
        single = NetfluxODE(model.topology, wb[b], n, ec50, ymax, tau)(torch.tensor(0.0), yb[b])
        torch.testing.assert_close(batched[b], single, rtol=1e-12, atol=1e-12)


def test_gradients_flow_through_simulation(examples):
    sim = netflux.Simulator(examples["exampleNet"])
    weight = sim.weight.clone()
    weight[0] = 0.8
    sim.weight = weight.requires_grad_(True)
    result = sim.run(5, 0.5)
    (grad,) = torch.autograd.grad(result["A"][-1], sim.weight)
    # dA/dt = w1 - A  =>  A(5) = w1 (1 - e^-5)
    assert float(grad[0]) == pytest.approx(1 - math.exp(-5), rel=1e-2)
    assert float(grad[1]) == pytest.approx(0.0, abs=1e-9)
