from pathlib import Path

import pytest

import netflux
from netflux import ModelError, convert_sbml_qual, import_sbml_qual, import_sif, read_model, to_sif

from .conftest import DATA, complete_fixtures, fixture_id

FIXTURES = complete_fixtures()


@pytest.mark.skipif(not FIXTURES, reason="Autogenerated models folder not available")
@pytest.mark.parametrize("xls", FIXTURES, ids=fixture_id)
def test_import_sif_reproduces_matlab_model(xls):
    sif = Path(f"{xls.with_suffix('')}.sif")
    expected = read_model(xls)
    imported = import_sif(sif)
    assert imported.species_ids == expected.species_ids
    assert [r.rule for r in imported.reactions] == [r.rule for r in expected.reactions]
    assert to_sif(imported) == sif.read_text()


def test_import_sif_and_gates(tmp_path):
    sif = tmp_path / "net.sif"
    sif.write_text("A\t1\tB\nrcn2\t1\tD\nB\t1\trcn2\nC\t-1\trcn2\nD\t-1\tA\n\n")
    model = import_sif(sif)
    assert model.species_ids == ["A", "B", "C", "D"]
    assert [r.rule for r in model.reactions] == ["A => B", "B & !C => D", "!D => A"]
    assert model.reaction_ids == ["r1", "r2", "r3"]
    r = model.reactions[0]
    assert (r.weight, r.n, r.ec50) == (1.0, 1.4, 0.5)
    assert to_sif(model) == "A\t1\tB\nrcn2\t1\tD\nB\t1\trcn2\nC\t-1\trcn2\nD\t-1\tA\n"


def test_import_sif_keeps_species_containing_rcn(tmp_path):
    sif = tmp_path / "net.sif"
    sif.write_text("Lrcn5\t1\tB\n")
    assert import_sif(sif).species_ids == ["B", "Lrcn5"]


def test_import_sif_round_trips_and_gates(examples, tmp_path):
    original = examples["ryall_cardiomyocyte_hypertrophy_jbc2012"]
    path = tmp_path / "ryall.sif"
    path.write_text(to_sif(original))
    imported = import_sif(path)

    def structure(model):
        topo, ids = model.topology, model.species_ids
        return {
            (tuple(sorted((ids[i], neg) for i, neg in r.inputs)), ids[r.products[0]])
            for r in topo.rules
            if r.inputs and len(r.products) == 1
        }

    assert structure(imported) == structure(original)
    assert any(" & " in r.rule for r in imported.reactions)


def test_import_sif_bad_line(tmp_path):
    sif = tmp_path / "bad.sif"
    sif.write_text("A 1\n")
    with pytest.raises(ModelError):
        import_sif(sif)


def test_import_sbml_qual():
    pytest.importorskip("libsbml")
    model = import_sbml_qual(DATA / "toy_qual.xml")
    assert model.species_ids == ["A", "B", "C", "D", "E"]
    assert [r.rule for r in model.reactions] == ["A => B", "!B => C", "C => D", "A => E", "!D => E"]
    assert any("tr4" in w and "2 inputs" in w for w in model.warnings)


def test_import_sbml_qual_rejects_plain_sbml(tmp_path):
    pytest.importorskip("libsbml")
    plain = tmp_path / "plain.xml"
    plain.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<sbml xmlns="http://www.sbml.org/sbml/level3/version1/core" level="3" version="1">'
        '<model id="m"/></sbml>'
    )
    with pytest.raises(ModelError):
        import_sbml_qual(plain)


def test_convert_sbml_qual(tmp_path):
    pytest.importorskip("libsbml")
    folder = convert_sbml_qual(DATA / "toy_qual.xml", tmp_path / "out")
    assert sorted(p.name for p in folder.iterdir()) == [
        "toy_qual Netflux.sif",
        "toy_qual Netflux.xlsx",
        "toy_qual Netflux_nodeAttributes.txt",
    ]
    model = read_model(folder / "toy_qual Netflux.xlsx")
    assert model.species_ids == ["A", "B", "C", "D", "E"]
    assert (folder / "toy_qual Netflux.sif").read_text().splitlines()[1] == "B\t-1\tC"
    assert netflux.simulate(model, 1).y.shape == (11, 5)
