"""Port of exportPythonODE.m: standalone PyTorch code (``<name>.py``, ``_params.py``, ``_run.py``)."""

from __future__ import annotations

import datetime as _dt
import keyword
from pathlib import Path

from .model import Model
from .paths import output_path

__all__ = ["python_ode_sources", "export_python_ode", "python_variable_names"]

RESERVED_NAMES = frozenset(
    {"t", "y", "tau", "ymax", "w", "n", "EC50", "rpar", "dydt", "torch", "act", "inhib", "OR", "AND"}
)


def python_variable_names(species_ids: list[str]) -> list[str]:
    """Safe, unique Python names for species IDs (unchanged where possible)."""

    def ok(name: str) -> bool:
        return name.isidentifier() and not keyword.iskeyword(name) and name not in RESERVED_NAMES

    taken = {s for s in species_ids if ok(s)}
    names: list[str] = []
    used: set[str] = set()
    for i, sid in enumerate(species_ids):
        if ok(sid) and sid not in used:
            name = sid
        else:
            name = f"{sid}_" if sid.isidentifier() else f"s{i}"
            while name in used or name in taken or not ok(name):
                name += "_"
        used.add(name)
        names.append(name)
    return names


def _reaction_terms(model: Model, var: list[str]) -> list[str]:
    terms = []
    for j, rule in enumerate(model.topology.rules):
        if not rule.reactants:
            terms.append(f"w[{j}]")
            continue
        parts = [
            f"{'inhib' if neg else 'act'}(y[{var[i]}], rpar[:, {j}])"
            for i, neg in zip(rule.reactants, rule.negated)
        ]
        terms.append(parts[0] if len(parts) == 1 else f"AND(w[{j}], [{', '.join(parts)}])")
    return terms


def _species_input(producers: tuple[int, ...], terms: list[str]) -> str:
    if not producers:
        return "0"
    expr = terms[producers[-1]]
    for j in reversed(producers[:-1]):  # OR(r1, OR(r2, r3)), as MATLAB nests them
        expr = f"OR({terms[j]}, {expr})"
    return expr


_HELPERS = '''

# utility functions

def act(x, rpar):
    w, n, EC50 = rpar[0], rpar[1], rpar[2]
    x = torch.clamp(x, min=0)
    beta = (EC50**n - 1) / (2 * EC50**n - 1)
    K_n = beta - 1  # K**n, where K = (beta - 1)**(1/n)
    fact = w * beta * x**n / (K_n + x**n)
    return torch.minimum(fact, w)


def inhib(x, rpar):
    return rpar[0] - act(x, rpar)


def OR(x, y):
    return x + y - x * y


def AND(w, reactList):
    if w == 0:
        return torch.zeros_like(w)
    return torch.stack(reactList).prod() / w ** (len(reactList) - 1)
'''


def _floats(values) -> str:
    return "[" + ", ".join(repr(float(v)) for v in values) + "]"


def python_ode_sources(model: Model, name: str = "NetfluxODE") -> dict[str, str]:
    """``{filename: source}`` for the three files."""
    if not name.isidentifier() or keyword.iskeyword(name):
        raise ValueError(f"module name {name!r} must be a valid Python identifier")
    stamp = f"# Automatically generated by Netflux on {_dt.date.today().isoformat()}"
    var = python_variable_names(model.species_ids)
    terms = _reaction_terms(model, var)

    ode = [f"# {name}.py", stamp, f"# Model: {model.name}", "import torch", "", ""]
    ode.append("def ODEfunc(t, y, tau, ymax, w, n, EC50):")
    ode.append("    rpar = torch.stack([w, n, EC50])")
    ode += [f"    {v} = {i}" for i, v in enumerate(var)]
    ode.append("    dydt = torch.zeros_like(y)")
    for v, producers in zip(var, model.topology.producers):
        rhs = _species_input(producers, terms)
        ode.append(f"    dydt[{v}] = ({rhs} * ymax[{v}] - y[{v}]) / tau[{v}]")
    ode.append("    return dydt")
    ode_src = "\n".join(ode) + _HELPERS

    species = model.species
    reactions = model.reactions
    params = [
        f"# {name}_params.py",
        stamp,
        "import torch",
        "",
        "",
        "def loadParams():",
        "    # species parameters",
        f"    speciesNames = {model.species_ids!r}",
        f"    tau = torch.tensor({_floats(s.tau for s in species)}, dtype=torch.float64)",
        f"    ymax = torch.tensor({_floats(s.ymax for s in species)}, dtype=torch.float64)",
        f"    y0 = torch.tensor({_floats(s.y0 for s in species)}, dtype=torch.float64)",
        "",
        "    # reaction parameters",
        f"    reactionIDs = {model.reaction_ids!r}",
        f"    w = torch.tensor({_floats(r.weight for r in reactions)}, dtype=torch.float64)",
        f"    n = torch.tensor({_floats(r.n for r in reactions)}, dtype=torch.float64)",
        f"    EC50 = torch.tensor({_floats(r.ec50 for r in reactions)}, dtype=torch.float64)",
        "    return speciesNames, tau, ymax, y0, w, n, EC50",
    ]
    params_src = "\n".join(params) + "\n"

    run = [
        f"# {name}_run.py",
        stamp,
        "import matplotlib.pyplot as plt",
        "import torch",
        "from torchdiffeq import odeint",
        "",
        f"import {name}",
        f"import {name}_params",
        "",
        f"speciesNames, tau, ymax, y0, w, n, EC50 = {name}_params.loadParams()",
        "",
        "# Run single simulation",
        "tspan = [0.0, 10.0]",
        "t = torch.linspace(tspan[0], tspan[1], 151, dtype=torch.float64)",
        "y = odeint(",
        f"    lambda t, y: {name}.ODEfunc(t, y, tau, ymax, w, n, EC50),",
        "    y0, t, method='dopri5', rtol=1e-6, atol=1e-8,",
        ")",
        "",
        "fig, ax = plt.subplots()",
        "ax.plot(t.numpy(), y.numpy())",
        "ax.set(xlabel='Time', ylabel='Fractional activation')",
        "ax.legend(speciesNames)",
        "plt.show()",
    ]
    run_src = "\n".join(run) + "\n"
    return {f"{name}.py": ode_src, f"{name}_params.py": params_src, f"{name}_run.py": run_src}


def export_python_ode(
    model: Model, directory: str | Path | None = None, name: str = "NetfluxODE"
) -> list[Path]:
    directory = output_path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    written = []
    for filename, source in python_ode_sources(model, name).items():
        target = directory / filename
        target.write_text(source, newline="\n")
        written.append(target)
    return written
